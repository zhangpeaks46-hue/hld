<?php
/**
 * 任务书提示词构建器
 * 根据论文名和用户上传的模板，构造AI提示词
 */
class TaskbookPromptBuilder
{
    /**
     * 构建任务书生成提示词
     *
     * @param string $thesisTitle 论文题目
     * @param string|null $templateText 模板文本内容（如有）
     * @return array ['system' => string, 'user' => string]
     */
    public static function build($thesisTitle, $templateText = null)
    {
        $system = "你是一位经验丰富的大学毕业论文指导教师和学术管理专家。"
            . "你擅长根据论文题目撰写规范的毕业设计（论文）任务书。"
            . "请严格按照 JSON 格式输出，不要输出任何额外解释文字。";

        $user = "请根据以下论文题目，生成一份完整的毕业设计（论文）任务书。\n\n"
            . "【论文题目】\n" . $thesisTitle . "\n\n";

        if ($templateText) {
            $user .= "【任务书模板内容】\n"
                . "以下是一份任务书模板的内容，请根据模板的格式和字段要求填充内容：\n"
                . $templateText . "\n\n"
                . "请按照模板中的字段名称和结构，将AI生成的任务书内容以JSON格式输出。\n"
                . "每个字段对应模板中的一个区域，value为填充的具体内容。\n\n";
        } else {
            $user .= "请生成包含以下所有板块的任务书内容：\n\n";
        }

        $user .= "请按以下 JSON 结构输出：\n"
            . "{\n"
            . "  \"thesis_title\": \"" . $thesisTitle . "\",\n"
            . "  \"topic_source\": \"课题来源（如：科研项目/企业委托/自选课题/实验室项目等）\",\n"
            . "  \"requirements\": \"基本任务与要求（300-500字，明确毕业设计应完成的主要任务、技术要求、成果形式等）\",\n"
            . "  \"research_content\": \"研究内容（400-600字，详细描述需要研究的主要方向、关键技术、研究方法等）\",\n"
            . "  \"requirements_analysis\": \"需求分析（300-500字，分析课题的背景、国内外现状、研究意义和应用需求）\",\n"
            . "  \"outline_design\": \"概要设计（300-500字，描述系统的总体架构、模块划分、技术路线、开发环境等）\",\n"
            . "  \"schedule\": [\n"
            . "    {\"phase\": \"第1-2周\", \"task\": \"查阅文献资料，了解课题背景\"},\n"
            . "    {\"phase\": \"第3-4周\", \"task\": \"完成开题报告，确定研究方案\"},\n"
            . "    {\"phase\": \"第5-8周\", \"task\": \"完成系统需求分析与概要设计\"},\n"
            . "    {\"phase\": \"第9-12周\", \"task\": \"完成核心功能开发与编码实现\"},\n"
            . "    {\"phase\": \"第13-14周\", \"task\": \"系统测试与优化\"},\n"
            . "    {\"phase\": \"第15-16周\", \"task\": \"撰写毕业论文，准备答辩材料\"}\n"
            . "  ],\n"
            . "  \"references\": [\n"
            . "    \"参考文献1（按GB/T 7714格式）\",\n"
            . "    \"参考文献2\",\n"
            . "    \"参考文献3\",\n"
            . "    \"参考文献4\",\n"
            . "    \"参考文献5\",\n"
            . "    \"参考文献6\",\n"
            . "    \"参考文献7\",\n"
            . "    \"参考文献8\",\n"
            . "    \"参考文献9\",\n"
            . "    \"参考文献10\"\n"
            . "  ]\n"
            . "}";

        return ['system' => $system, 'user' => $user];
    }
}